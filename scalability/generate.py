#!/usr/bin/env python3
"""Generates larger BPMN models for layer 6, with a fresh identifier per node.

Process: K webshop stages in sequence. A stage is the process of
L6_Presentation: OrderCreated -> parallel split -> {NotifyWarehouse,
event-based gateway with the alternatives message, timer and signal}. The
message alternative of stage i leads through a Continue task to OrderCreated
of stage i+1. With the Start event the model has 8K nodes, so K = 1 has as
many nodes as L6_Presentation and K = 2, 3, 4 twice, three and four times as
many.

Encoding: Instance_Start draws a fresh identifier for every node of the new
instance and emits the structure of the process as persistent facts over
these identifiers (!Next for a sequence flow, !Split for a parallel split,
!Alt for an alternative of an event-based gateway). A token is Token(~node).
The four rules are the same for every K; only the facts of Instance_Start
grow with the process. Deadlines are left out: the timing lemmas are proven
in L6_Presentation and do not depend on the size of the process.

    python generate.py [K ...]      (default: 1 2 3 4)
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def process(k):
    """Nodes and flows of K stages: (nodes, sequence flows, splits, gateways)."""
    nodes = ["Start"]
    seq = [("Start", "OrderCreated1")]
    splits = []    # (split, branch 1, branch 2)
    gateways = []  # (gateway, [alternatives])
    for i in range(1, k + 1):
        nodes += [f"OrderCreated{i}", f"Split{i}", f"NotifyWarehouse{i}", f"EBG{i}",
                  f"message{i}", f"timer{i}", f"signal{i}"]
        seq.append((f"OrderCreated{i}", f"Split{i}"))
        splits.append((f"Split{i}", f"NotifyWarehouse{i}", f"EBG{i}"))
        gateways.append((f"EBG{i}", [f"message{i}", f"timer{i}", f"signal{i}"]))
        if i < k:
            nodes.append(f"Continue{i}")
            seq += [(f"message{i}", f"Continue{i}"), (f"Continue{i}", f"OrderCreated{i + 1}")]
    return nodes, seq, splits, gateways


def theory(k):
    nodes, seq, splits, gateways = process(k)
    edges = (seq + [(s, b) for s, b1, b2 in splits for b in (b1, b2)]
             + [(g, a) for g, alts in gateways for a in alts])
    v = lambda n: f"~{n}"
    last = f"message{k}"

    premises = ", ".join(f"Fr({v(n)})" for n in nodes)
    actions = ([f"Start({v('Start')})", f"Last({v(last)})", f"Enter({v('Start')})"]
               + [f"EdgeDef({v(a)}, {v(b)})" for a, b in edges]
               + [f"Gateway({v(g)})" for g, _ in gateways])
    facts = ([f"Token({v('Start')})"]
             + [f"!Next({v(a)}, {v(b)})" for a, b in seq]
             + [f"!Split({v(s)}, {v(b1)}, {v(b2)})" for s, b1, b2 in splits]
             + [f"!Alt({v(g)}, {v(a)})" for g, alts in gateways for a in alts])
    sep = ",\n      "

    return f"""theory L6_Scaled_x{k}
begin

/*
 * Generated by scalability/generate.py, K = {k}.
 *
 * Layer 6 with a larger BPMN model: {k} webshop stage(s) in sequence,
 * {len(nodes)} nodes, {len(edges)} admissible transitions, {len(splits)} parallel split(s) and
 * {len(gateways)} event-based gateway(s). Every node has a fresh identifier per
 * instance, and a token is Token(~node). The dishonest participant may fire
 * any enabled transition of any instance in any order.
 */

// A new process instance: a fresh identifier for every node, and the
// structure of the process over these identifiers
rule Instance_Start:
    [ {premises} ]
  --[ {sep.join(actions)} ]->
    [ {sep.join(facts)} ]

// Sequence flow
rule Step_Sequence:
    [ Token(n), !Next(n, m) ]
  --[ Transition(n, m), Enter(m) ]->
    [ Token(m) ]

// Parallel split: one token per outgoing branch
rule Step_Split:
    [ Token(s), !Split(s, b1, b2) ]
  --[ Transition(s, b1), Transition(s, b2), Enter(b1), Enter(b2) ]->
    [ Token(b1), Token(b2) ]

// Event-based gateway: the alternatives compete for the single gateway token
rule Step_EBG:
    [ Token(g), !Alt(g, a) ]
  --[ Transition(g, a), Takes(g, a), Enter(a) ]->
    [ Token(a) ]

// The process is executable: a token reaches the last node of the chain
lemma executable:
  exists-trace
  "Ex n #i #j. Last(n) @ #i & Enter(n) @ #j"

// One token per node: a token enters every node at most once. Induction
// keeps the proof linear in the size of the process.
lemma one_token_per_node [use_induction, reuse]:
  "All n #i #j. Enter(n) @ #i & Enter(n) @ #j ==> #i = #j"

// Only transitions of the BPMN model can take effect
lemma admissible_only:
  "All n m #i. Transition(n, m) @ #i ==> Ex #j. EdgeDef(n, m) @ #j"

// R2 (safety): of the alternatives of every gateway exactly one takes effect
lemma gateway_exclusivity:
  "All g a1 a2 #i #j. Takes(g, a1) @ #i & Takes(g, a2) @ #j ==>
      a1 = a2 & #i = #j"

end
"""


if __name__ == "__main__":
    for k in [int(a) for a in sys.argv[1:]] or [1, 2, 3, 4]:
        path = HERE / f"L6_Scaled_x{k}.spthy"
        path.write_text(theory(k), encoding="utf-8", newline="\n")
        nodes, seq, splits, gateways = process(k)
        print(f"{path.name}: {len(nodes)} nodes, {len(seq) + 2 * len(splits) + 3 * len(gateways)}"
              f" transitions, {len(gateways)} gateway(s)")
